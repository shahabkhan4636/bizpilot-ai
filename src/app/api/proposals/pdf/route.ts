import { NextResponse } from "next/server";
import { requireAuth } from "@/lib/auth";
import { all, get } from "@/lib/db";
import { renderPdf, type PdfLine } from "@/lib/pdf";
import { formatMoney, formatDate } from "@/lib/utils";
import { audit } from "@/lib/audit";

/** Real PDF generation (no headless browser): see src/lib/pdf.ts. */
export async function GET(request: Request) {
  let ctx;
  try {
    ctx = await requireAuth();
  } catch {
    return NextResponse.json({ error: "Not signed in" }, { status: 401 });
  }
  const orgId = ctx.membership.organization_id;
  const id = new URL(request.url).searchParams.get("id");
  if (!id) return NextResponse.json({ error: "Missing id" }, { status: 400 });

  const proposal = get<{
    title: string; client_name: string; client_email: string | null; summary: string | null; scope: string | null;
    terms: string | null; currency: string; subtotal_cents: number; tax_cents: number; total_cents: number;
    status: string; version: number; created_at: string; share_token: string | null;
  }>(
    `select title, client_name, client_email, summary, scope, terms, currency, subtotal_cents, tax_cents,
            total_cents, status, version, created_at, share_token
       from proposals where id = ? and organization_id = ?`,
    [id, orgId]
  );
  if (!proposal) return NextResponse.json({ error: "Not found" }, { status: 404 });

  const items = all<{ description: string; quantity: number; unit_price_cents: number; amount_cents: number }>(
    "select description, quantity, unit_price_cents, amount_cents from proposal_items where proposal_id = ? and organization_id = ? order by sort_order asc",
    [id, orgId]
  );

  const lines: PdfLine[] = [
    { text: ctx.membership.organization_name, size: 18, bold: true, gap: 2 },
    { text: "Proposal", size: 11, gap: 6, rule: true },
    { text: proposal.title, size: 14, bold: true, gap: 4 },
    { text: `Prepared for: ${proposal.client_name}${proposal.client_email ? ` <${proposal.client_email}>` : ""}`, size: 10, gap: 2 },
    { text: `Date: ${formatDate(proposal.created_at)}    Version: ${proposal.version}    Status: ${proposal.status}`, size: 10, gap: 10 },
  ];

  if (proposal.summary) lines.push({ text: "Summary", size: 11, bold: true, gap: 3, rule: true }, { text: proposal.summary, gap: 8 });

  lines.push({ text: "Line items", size: 11, bold: true, gap: 3, rule: true });
  for (const item of items) {
    lines.push({
      text: `${item.description}  |  ${item.quantity} x ${formatMoney(item.unit_price_cents, proposal.currency)} = ${formatMoney(item.amount_cents, proposal.currency)}`,
      gap: 2,
    });
  }
  lines.push(
    { text: "", gap: 4, rule: true },
    { text: `Subtotal: ${formatMoney(proposal.subtotal_cents, proposal.currency)}`, align: "right", gap: 2 },
    { text: `Tax: ${formatMoney(proposal.tax_cents, proposal.currency)}`, align: "right", gap: 2 },
    { text: `Total: ${formatMoney(proposal.total_cents, proposal.currency)}`, bold: true, align: "right", gap: 12 }
  );

  if (proposal.scope) lines.push({ text: "Scope of work", size: 11, bold: true, gap: 3, rule: true }, { text: proposal.scope, gap: 8 });
  if (proposal.terms) lines.push({ text: "Terms", size: 11, bold: true, gap: 3, rule: true }, { text: proposal.terms, gap: 8 });

  if (proposal.share_token) {
    lines.push({ text: "Accept online", size: 11, bold: true, gap: 3, rule: true });
    lines.push({ text: `Open /p/${proposal.share_token} on this deployment to accept or decline this proposal.`, size: 9 });
  }
  lines.push({ text: "", gap: 10 }, { text: "Generated by BizPilot AI", size: 8 });

  const bytes = renderPdf(lines);
  audit({ organizationId: orgId, actorId: ctx.user.id, action: "proposal.pdf", targetType: "proposal", targetId: id });

  return new NextResponse(Buffer.from(bytes), {
    headers: {
      "content-type": "application/pdf",
      "content-disposition": `attachment; filename="proposal-${id.slice(0, 8)}.pdf"`,
      "cache-control": "no-store",
    },
  });
}
